CFG = style.ROOT / "01_data_generation" / "config"
SHAPE = style.ROOT / "outputs" / "03_shape_validation"
ATTR = style.ROOT / "outputs" / "04_attribution_validation"
LABELS = yaml.safe_load((style.ROOT / "04_attribution_validation" / "config" / "labels.yaml").read_text())
METHODS = list(LABELS["methods"])
VARIANTS = ["MGM-PC-Stable", "MGM-CPC-Stable", "MGM-MPC-Stable", "MGM-PC-Max-Stable"]
OWN = {"full_set": "source", "reference_subsample": "source", "astronaut_set": "selected"}
POWER_FLOOR = 0.8
DAGGER = r"$^{\dagger}$"


def esc(s):
    return re.sub(r"([&%#_$])", r"\\\1", str(s))


def fnum(x, d=2):
    return "--" if pd.isna(x) else f"{x:.{d}f}"


def ms(m, se, d=2):
    return "--" if pd.isna(m) else f"{m:.{d}f} ({'--' if pd.isna(se) else f'{se:.{d}f}'})"


def mcse(x):
    x = pd.Series(x).dropna()
    return x.std(ddof=1) / np.sqrt(len(x)) if len(x) > 1 else np.nan


def binom_se(p, n):
    return np.sqrt(p * (1 - p) / n)


def names():
    n = pd.read_csv(CFG / "nodes.csv")
    return dict(zip(n["id"], n["name"])), dict(zip(n["id"], n["level"])), dict(zip(n["id"], n["scale"]))


# Page layout per table: long tables break across pages, wide ones are set on landscape pages.
LAYOUT = {label: {"long": True, "landscape": True, "size": r"\footnotesize"} for label in (
    "tab:supp-features", "tab:supp-implications", "tab:supp-discovery", "tab:supp-confounding",
    "tab:supp-attribution", "tab:supp-attributionb", "tab:supp-contrasts", "tab:supp-oracle", "tab:supp-credit")}
for label in ("tab:supp-discovery", "tab:supp-contrasts"):  # the two widest; 8 pt keeps them inside a landscape page
    LAYOUT[label].update(size=r"\scriptsize", sep="4pt")


class Table:
    def __init__(self, label, caption, colspec, head, notes):
        self.label, self.caption, self.colspec, self.head, self.notes = label, caption, colspec, head, notes
        self.lines, self.n = [], 0
        self.size = r"\footnotesize"

    def row(self, *cells, indent=False):
        self.lines.append((r"\quad " if indent else "") + " & ".join(str(c) for c in cells) + r" \\")
        self.n += 1

    def raw(self, line):
        self.lines.append(line)

    def span(self, text, italic=False, ncols=None):
        k = ncols or len(re.findall(r"[lrc]", re.sub(r"@\{[^}]*\}", "", self.colspec)))
        t = rf"\textit{{{text}}}" if italic else rf"\textbf{{{text}}}"
        self.lines.append(rf"\multicolumn{{{k}}}{{l}}{{{t}}}\\")

    def render(self, script_name):
        lay = LAYOUT.get(self.label, {})
        size = lay.get("size", self.size) + (rf"\setlength{{\tabcolsep}}{{{lay['sep']}}}" if "sep" in lay else "")
        top = [rf"% Generated by 05_figures/supp_tables.py ({script_name}); edit the script, not this file.",
               r"% Preamble: \usepackage{booktabs,threeparttable,longtable,pdflscape}"]
        if lay.get("long"):
            body = [r"\begingroup", size, r"\setlength{\LTcapwidth}{\linewidth}",
                    rf"\begin{{longtable}}{{{self.colspec}}}", rf"\caption{{{self.caption}}}\label{{{self.label}}}\\",
                    r"\toprule", *self.head, r"\midrule", r"\endfirsthead",
                    r"\toprule", *self.head, r"\midrule", r"\endhead",
                    r"\bottomrule", r"\endfoot", *self.lines, r"\end{longtable}",
                    r"\par\footnotesize", *[f"{n}\\par" for n in self.notes], r"\endgroup"]
        else:
            body = [r"\begin{table}[p]", r"\centering", size, r"\begin{threeparttable}",
                    rf"\caption{{{self.caption}}}", rf"\label{{{self.label}}}",
                    rf"\begin{{tabular}}{{{self.colspec}}}", r"\toprule", *self.head, r"\midrule", *self.lines,
                    r"\bottomrule", r"\end{tabular}", r"\begin{tablenotes}\footnotesize",
                    *[rf"\item {n}" for n in self.notes], r"\end{tablenotes}", r"\end{threeparttable}",
                    r"\end{table}"]
        if lay.get("landscape"):
            body = [r"\begin{landscape}", *body, r"\end{landscape}"]
        return "\n".join(top + body + [""])


def hdr(*lines):
    """A header cell set on several short lines, so wide labels do not set the column width."""
    return r"\shortstack{" + r"\\{}".join(lines) + "}"  # {} stops a following "[" being read as a skip


def ds_label(ds):
    return esc(LABELS["datasets"][ds])


def ds_pop(ds, pop):
    return ds_label(ds) + (", source population" if (ds == "astronaut_set" and pop == "source") else "")


# Table 1: features of the adapted DAG and its edge list
def build_t1():
    nm, level, _ = names()
    fs = pd.read_csv(DATA / "feature_sets.csv")
    edges = pd.read_csv(CFG / "edges.csv")
    sim = pd.read_csv(CFG / "simulation_edges.csv")
    sim_keys = set(zip(sim["parent"], sim["child"]))
    t = Table("tab:supp-features", "Features of the adapted DAG and its edges.", r"@{}l l l c c@{}",
              [r"Feature & Scale & Role & Ancestor of outcome & Era-fixed \\"], [
        r"Era-fixed features take one value within a mission era. Coefficients are those of the simulation; "
        r"-- marks an edge without a coefficient.",
        rf"{DAGGER}Edge added for the simulation and absent from the source DAG."])
    for r in fs.itertuples():
        t.row(esc(nm[r.id]), r.scale, esc(r.role), "Yes" if r.in_ancestor_set else "No",
              "Yes" if level.get(r.id) == "era_fixed" else "No")
    t.raw(r"\midrule")
    t.raw(r"Parent $\to$ child & Type & Child scale & Coefficient & \\")
    t.raw(r"\midrule")
    all_edges = pd.concat([edges, sim], ignore_index=True)
    for r in all_edges.itertuples():
        mark = DAGGER if (r.parent, r.child) in sim_keys else ""
        coef = "--" if pd.isna(r.coef) else f"{r.coef:g}"
        t.row(rf"{esc(nm[r.parent])} $\to$ {esc(nm[r.child])}{mark}", esc(r.edge_type), r.child_scale, coef, "")
    return t.render("supp_table1_features.tex"), t.n


# Table 2: implication-test calibration and power
def build_t2():
    nm, _, scale = names()
    cal = pd.read_csv(SHAPE / "implication_calibration_summary.csv").set_index("dataset")
    summ = pd.read_csv(SHAPE / "summary.csv").query("variant == 'MGM-PC-Stable'").set_index("dataset")
    power = pd.read_csv(SHAPE / "power_by_edge.csv")
    t = Table("tab:supp-implications", "Calibration and power of the testable-implication tests.",
              r"@{}l rr r@{}", [r"Data set & KS rejection rate & Raw rejection rate & Replicates with any unexpected rejection \\"], [
        "Rejection rates are over 50 replicates (binomial MCSE for the KS rate and the unexpected-rejection rate; "
        "Monte Carlo SE of the mean for the raw rate). Unexpected rejections are for MGM-PC-Stable.",
        rf"Power: detection rate of each deleted edge by data set; {DAGGER}detected in fewer than "
        f"{POWER_FLOOR:.0%} of replicates. Binary child nodes are flagged."])
    for ds in style.DATASETS:
        c, s = cal.loc[ds], summ.loc[ds]
        t.row(ds_label(ds), ms(c.ks_rejection_rate, binom_se(c.ks_rejection_rate, c.replicates), 3),
              ms(c.raw_rejection_rate_mean, c.raw_rejection_rate_se, 3),
              ms(s.any_unexpected_rejection_rate, binom_se(s.any_unexpected_rejection_rate, s.replicates), 3))
    t.raw(r"\midrule")
    t.raw(r"Deleted edge & " + " & ".join(ds_label(d) for d in style.DATASETS) + r" \\")
    t.raw(r"\midrule")
    wide = power.pivot(index="edge", columns="dataset", values="detection_rate")
    n = int(cal["replicates"].iloc[0])
    kind = dict(zip(zip(*[pd.read_csv(CFG / "edges.csv")[k] for k in ("parent", "child")]),
                    pd.read_csv(CFG / "edges.csv")["child_scale"]))
    for edge, r in wide.iterrows():
        p, c = edge.split(" -> ")
        binary = kind.get((p, c), scale.get(c)) == "binary"
        cells = [f"{fnum(r[d])} ({fnum(binom_se(r[d], n))})" + (DAGGER if r[d] < POWER_FLOOR else "")
                 for d in style.DATASETS]
        t.row(rf"{esc(nm[p])} $\to$ {esc(nm[c])}" + (" (binary child)" if binary else ""), *cells)
    return t.render("supp_table2_implications.tex"), t.n


# Table 4: causal discovery by variant and per-edge recovery
def build_t4():
    nm, _, _ = names()
    summ = pd.read_csv(SHAPE / "summary.csv")
    rep = pd.read_csv(SHAPE / "per_replicate.csv")
    t = Table("tab:supp-discovery", "Causal discovery against the true analysis graph.",
              r"@{}l l rrr rr rr r@{}", [
        r" & & & & & \multicolumn{2}{c}{Compelled edges} & \multicolumn{2}{c}{Implications held (share)} & \\",
        r"\cmidrule(lr){6-7}\cmidrule(lr){8-9}",
        "Variant & Data set & " + " & ".join([hdr("Adj.", "precision"), hdr("Adj.", "recall"), hdr("Orient.", "agreement"),
                                             "Reversed", "Unoriented", hdr("Truth held", "by learned"),
                                             hdr("Learned held", "by truth"), hdr("Comparison", "available")]) + r" \\"], [
        "Cells are mean (MCSE) over replicates. Compelled edges are counts. Implication shares are computed per "
        "replicate and averaged over replicates where the comparison was available (n of 50 in the last column). "
        "Edge-by-edge recovery rates are given in Supplementary Data 1."])
    for v in VARIANTS:
        for ds in style.DATASETS:
            s = summ[(summ.variant == v) & (summ.dataset == ds)].iloc[0]
            r = rep[(rep.variant == v) & (rep.dataset == ds)]
            a = r["truth_held_by_learned"] / r["truth_implications"]
            b = r["learned_held_by_truth"] / r["learned_implications"]
            t.row(v if ds == style.DATASETS[0] else "", ds_label(ds),
                  ms(s.adjacency_precision_mean, s.adjacency_precision_se),
                  ms(s.adjacency_recall_mean, s.adjacency_recall_se),
                  ms(s.orientation_agreement_mean, s.orientation_agreement_se),
                  ms(s.compelled_reversed_mean, s.compelled_reversed_se, 1),
                  ms(s.compelled_unoriented_mean, s.compelled_unoriented_se, 1),
                  ms(a.mean(), mcse(a)), ms(b.mean(), mcse(b)),
                  f"{int(round(s.comparison_available_rate * s.replicates))} of {int(s.replicates)}")
    return t.render("supp_table4_discovery.tex"), t.n


# Table 5: confounding recovery
def build_t5():
    nm, _, _ = names()
    s = pd.read_csv(ATTR / "confounding_summary.csv")
    cred = pd.read_csv(ATTR / "confounding_reference_credits.csv")
    meta = json.loads((ATTR / "confounding_reference_meta.json").read_text())
    t = Table("tab:supp-confounding", "Recovery of confounders by ConfoundingSHAP.", r"@{}l l l rrr rr@{}", [
        r"Drug & Data set & Answer key & Confounder mass & Reference mass & Recovery & Crude effect & True effect \\"], [
        "Mass is the share of absolute credit placed on the answer key's confounders; recovery is the share of "
        "the key's confounders among the |C| covariates with the largest absolute credit. Cells are mean (MCSE) over runs. Reference mass "
        "comes from the true model; effects are for each data set's own population (source, or selected for the "
        "astronaut set). Direct keys hold common causes of treatment and outcome; any keys hold any common cause."])
    for r in s.sort_values(["treatment", "dataset"]).itertuples():
        pop = OWN[r.dataset]
        c = cred[(cred.treatment == r.treatment) & (cred.population == pop)]
        m = meta[f"{r.treatment}/{pop}"]
        for key in ("direct", "any"):
            ref = c.loc[c[f"{key}_common_cause"], "credit"].abs().sum() / c["credit"].abs().sum()
            t.row(esc(nm[r.treatment]) if key == "direct" else "", ds_label(r.dataset) if key == "direct" else "",
                  key, ms(getattr(r, f"mass_{key}_mean"), getattr(r, f"mass_{key}_mcse")), fnum(ref),
                  ms(getattr(r, f"recovery_{key}_mean"), getattr(r, f"recovery_{key}_mcse")),
                  fnum(m["crude"], 3), fnum(m["ate"], 3))
    return t.render("supp_table5_confounding.tex"), t.n


# Table 6: attribution accuracy, all-features and ancestors-only runs
METRICS6 = [("kendall_tau_b", r"$\tau_b$"), ("weighted_tau", "Weighted $\\tau$"), ("l1_distance", "L1"),
            ("top_k_recovery", "Top-5"), ("proximity_bias_index", "PBI"), ("non_ancestor_share", "Non-anc. share")]
FEATURE_SETS6 = [("all", "All"), ("ancestor", "Anc.")]
METHOD_ORDER6 = ["standard_shap", "ordering_only_shap", "ng_style_shap", "interventional_shap"]


def build_t6(scope="with_era"):
    s = pd.read_csv(ATTR / "summary.csv")
    s = s[(s.scope == scope) & s.method.isin(METHOD_ORDER6)]
    own = s[s.population == s.dataset.map(OWN)]
    src = s[(s.dataset == "astronaut_set") & (s.population == "source")]
    s = pd.concat([own, src]).set_index(["feature_set", "truth_type", "dataset", "population", "method"]).sort_index()
    era = "with" if scope == "with_era" else "without"
    suffix = "" if scope == "with_era" else "b"
    k = len(METRICS6)
    head = ["Data set & Method & Inputs & " + " & ".join(h for _, h in METRICS6) + r" \\"]
    t = Table(f"tab:supp-attribution{suffix}", f"Attribution accuracy against each truth, {era} mission era.",
              r"@{}l l l " + "r" * k + "@{}", head, [
        "Cells are mean (MCSE) over 50 replicates. Rank agreement is computed over the 16 ancestors for both inputs: "
        "All, the model was also given the 19 non-ancestors as inputs; Anc., ancestors only. Each data set is scored "
        "against its own population (source, or selected for the astronaut-set); astronaut-set rows are also "
        "scored against the source population. Non-ancestor share is the share of attribution credited to "
        "non-ancestors and applies to the all-features runs only. PBI: proximity bias index (positive = credit "
        "pooled near the outcome); top-5: recovery of the true top five."])
    order = [(d, p) for d in style.DATASETS for p in (["selected", "source"] if d == "astronaut_set" else [OWN[d]])]
    for truth in LABELS["truth_type"]:
        t.span(LABELS["truth_type"][truth], italic=True)
        for ds, pop in order:
            for m in METHOD_ORDER6:
                for fset, flabel in FEATURE_SETS6:
                    r = s.loc[(fset, truth, ds, pop, m)]
                    cells = ["--" if (key == "non_ancestor_share" and fset == "ancestor")
                             else ms(r[f"{key}_mean"], r[f"{key}_mcse"]) for key, _ in METRICS6]
                    first = m == METHOD_ORDER6[0] and fset == FEATURE_SETS6[0][0]
                    t.row(ds_pop(ds, pop) if first else "", esc(LABELS["methods"][m]) if fset == "all" else "",
                          flabel, *cells)
        if truth != list(LABELS["truth_type"])[-1]:
            t.raw(r"\addlinespace")
    return t.render(f"supp_table6{suffix}_{'attribution' if not suffix else 'without_era'}.tex"), t.n


def build_t6b():
    return build_t6("without_era")


# Table 7: paired contrasts
CONTRASTS = {"order_effect": "Ordering", "value_function_effect": "Value function",
             "prediction_value_function_effect": "Prediction value function"}


CONDITION_CONTRASTS = {"sample_size_effect": "Sample size", "selection_effect": "Selection",
                       "selection_effect_source_scored": "Selection, source-scored"}
METRIC_LABELS = {"kendall_tau_b": r"$\tau_b$", "top_k_recovery": "Top-5", "proximity_bias_index": "PBI",
                 "non_ancestor_share": "Non-ancestor share", "edges_detectable": "Detectable edges",
                 "adjacency_recall": "Adjacency recall", "adjacency_precision": "Adjacency precision",
                 "orientation_agreement": "Orientation agreement", "raw_rejection_rate": "Raw rejection rate"}


def contrast_files():
    return (pd.read_csv(ATTR / "contrasts.csv"), pd.read_csv(ATTR / "data_condition_contrasts.csv"),
            pd.read_csv(SHAPE / "data_condition_contrasts.csv"))


CO_PRIMARY = ["per_unit", "pop"]
COND_METRICS = ["kendall_tau_b", "proximity_bias_index", "non_ancestor_share"]


def build_t7():
    """The contrasts the text reports; the full grid (every truth, population and metric) is Supplementary Data 2."""
    paired, cond, shape = contrast_files()
    paired = paired[paired.truth_type.isin(CO_PRIMARY) & (paired.population == paired.dataset.map(OWN))
                    & (paired.feature_set == "ancestor")]
    cond = cond[cond.truth_type.isin(CO_PRIMARY) & cond.metric.isin(COND_METRICS)
                & cond.contrast.isin(["sample_size_effect", "selection_effect"])]
    t = Table("tab:supp-contrasts", "Paired contrasts between attribution methods and between data conditions.",
              r"@{}l l l l l r r l@{}", [
        "Data set & Set & Truth & Population & Contrast & " + hdr("Mean (MCSE)", r"[95\% CI]") + " & "
        + hdr("Truth difference", r"[95\% CI]") + r" & Classification \\"], [
        "Contrasts are paired within replicate (50 replicates); intervals are mean $\\pm$ 1.96 MCSE. Truth "
        "difference: paired difference between the contrast under the intervention-contrast and population-scaled "
        "truths. Set: ancestor or all features. Record-level rows are a sensitivity analysis and are not "
        "classified. Panel A: differences in Kendall's $\\tau_b$ between methods. Panel B: sample-size and "
        "selection effects on each metric, each data set scored against its own population (source, or selected "
        "for the astronaut-set); classification applies to $\\tau_b$ only and other metrics are descriptive. "
        "Panel C: the same effects on the shape-validation metrics for MGM-PC-Stable, which are not scored "
        "against a population. Contrasts: ordering, ordering-only minus standard SHAP; value function, causal "
        "interventional minus ordering-only SHAP; prediction value function, causal predictive minus ordering-only "
        "SHAP; sample size, reference-set minus full-set; selection, astronaut-set minus reference-set; selection, "
        "source-scored, the same with the astronaut-set scored against the source population. Shown: the two "
        "co-primary truths, each data set scored against its own population, ancestor set for method contrasts. "
        "Every contrast under every truth, population, feature set and metric is given in Supplementary Data 2."])
    ci = lambda r: f"{r.mean:.3f} ({fnum(r.mcse, 3)}) [{r.ci_low:.3f}, {r.ci_high:.3f}]"  # noqa: E731
    t.span("A  Method contrasts")
    for r in paired.itertuples():
        t.row(ds_label(r.dataset), r.feature_set, esc(LABELS["truth_type"].get(r.truth_type, r.truth_type)),
              r.population, esc(CONTRASTS.get(r.contrast, r.contrast)), ci(r),
              f"{r.truth_diff_mean:.3f} [{r.truth_diff_ci_low:.3f}, {r.truth_diff_ci_high:.3f}]",
              esc(r.classification))
    t.raw(r"\midrule")
    t.raw("Method & Metric & Truth & Set & Contrast & " + hdr("Mean (MCSE)", r"[95\% CI]") + " & "
          + hdr("Truth difference", r"[95\% CI]") + r" & Classification \\")
    t.raw(r"\midrule")
    t.span("B  Data-condition contrasts, attribution")
    order = {m: i for i, m in enumerate(METHODS)}
    for r in cond.assign(o=cond["method"].map(order)).sort_values(["o", "metric", "truth_type", "contrast"]).itertuples():
        td = "--" if pd.isna(r.truth_diff_mean) else (
            f"{r.truth_diff_mean:.3f} [{r.truth_diff_ci_low:.3f}, {r.truth_diff_ci_high:.3f}]")
        t.row(esc(LABELS["methods"][r.method]), METRIC_LABELS[r.metric], esc(LABELS["truth_type"][r.truth_type]),
              r.feature_set, CONDITION_CONTRASTS[r.contrast], ci(r), td, esc(r.classification))
    t.raw(r"\midrule")
    t.raw("Variant & Metric & & & Contrast & " + hdr("Mean (MCSE)", r"[95\% CI]") + r" & & \\")
    t.raw(r"\midrule")
    t.span("C  Data-condition contrasts, shape validation")
    for r in shape.itertuples():
        t.row(r.variant, METRIC_LABELS[r.metric], "", "", CONDITION_CONTRASTS[r.contrast], ci(r), "", "")
    return t.render("supp_table7_contrasts.tex"), t.n


# Table 8: oracle decomposition
METRICS8 = [("tau_oracle_truth", r"$\tau$ oracle--truth"), ("tau_fitted_truth", r"$\tau$ fitted--truth"),
            ("tau_fitted_oracle", r"$\tau$ fitted--oracle"), ("l1_fitted_oracle", "L1 fitted--oracle")]


def build_t8():
    o = pd.read_csv(ATTR / "oracle_decomposition.csv")
    o = o[(o.feature_set == "ancestor") & (o.population == o.dataset.map(OWN)) & o.method.isin(METHODS)]
    reps = o["replicate"].nunique()
    t = Table("tab:supp-oracle", "Decomposition of attribution error into model and method components.",
              r"@{}l l l rrrr@{}", [r"Truth & Data set & Method & " + " & ".join(h for _, h in METRICS8) + r" \\"], [
        f"Cells are mean (MCSE) over replicates 1--{reps}, ancestor set, each data set scored against its own "
        "population. Oracle: the method rerun with the true model in place of the fitted one on the same explained "
        "records; $\\tau$ is Kendall's $\\tau_b$."])
    for truth in LABELS["truth_type"]:
        for ds in style.DATASETS:
            for m in METHODS:
                g = o[(o.truth_type == truth) & (o.dataset == ds) & (o.method == m)]
                t.row(esc(LABELS["truth_type"][truth]) if (ds, m) == (style.DATASETS[0], METHODS[0]) else "",
                      ds_label(ds) if m == METHODS[0] else "", esc(LABELS["methods"][m]),
                      *[ms(g[k].mean(), mcse(g[k])) for k, _ in METRICS8])
    return t.render("supp_table8_oracle.tex"), t.n


