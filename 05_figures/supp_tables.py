"""Supplementary tables 1, 2, 4-8 as LaTeX (booktabs + threeparttable) in outputs/05_figures/.

Cells are mean (MCSE) over replicates unless stated. Binomial rates carry sqrt(p(1-p)/n). Display names
come from 04_attribution_validation/config/labels.yaml. Run from 05_figures/: python3 supp_tables.py [--only 5 6]
"""
